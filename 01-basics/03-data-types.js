// Question:
// Create one variable for each data type:
// string, number, boolean, null, and undefined.
// Print each variable and its type.

// Solution:
const nameString = "John Doe"; // string
const ageNumber = 30; // number
const isStudentBoolean = true; // boolean
const emptyValueNull = null; // null
let undefinedValue; // undefined

console.log(nameString,"type is ", typeof nameString); // John Doe string
console.log(ageNumber,"type is ", typeof ageNumber); // 30 number
console.log(isStudentBoolean,"type is ", typeof isStudentBoolean); // true boolean
console.log(emptyValueNull,"type is ", typeof emptyValueNull); // null object
console.log(undefinedValue,"type is ", typeof undefinedValue); // undefined undefined